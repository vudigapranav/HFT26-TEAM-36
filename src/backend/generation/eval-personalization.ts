// Personalization evaluation over the fixture portfolios in tests/fixtures/portfolios/eval/.
// Real pipeline: intake -> project evidence -> selection -> K5 certification on the configured runner.
//   RUNNER=docker node --env-file-if-exists=../../.env --import tsx generation/eval-personalization.ts [--live-ai] [out.md]
// Without --live-ai (or without a reachable provider) Stage B is skipped and selections are labelled deterministic.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import type { CandidateProfile, PrivateTask, Tier } from '../contracts/internal.js';
import type { Ports } from '../contracts/seams.js';
import { loadSeedBank } from '../api/seed-bank.js';
import { extractEvidence } from '../intake/evidence.js';
import { parsePortfolioDetailed, validPortfolio } from '../intake/portfolio.js';
import { chat } from '../llm/featherless.js';
import { runTestsInDocker } from '../runner/dockerRunner.js';
import { runTestsInE2B } from '../runner/e2bRunner.js';
import { createGenerator } from './generate.js';
import { withReceiptCache } from './receipts.js';
import { createValidationEngine } from './validate.js';

const live = process.argv.includes('--live-ai');
const out = process.argv.slice(2).find(a => a.endsWith('.md'));
const runTests = process.env.RUNNER === 'e2b' ? runTestsInE2B : runTestsInDocker;
const validateTask = withReceiptCache(createValidationEngine(runTests));
const down: Ports['chat'] = async () => ({ kind: 'unavailable', code: 'LLM_UNAVAILABLE', message: 'Stage B not used in this run' });
const tiers: Tier[] = ['novice', 'adept', 'master'];
const dir = new URL('../tests/fixtures/portfolios/eval/', import.meta.url);
const rows: string[] = [];
const baseline: string[] = [];
const summary: Record<string, string> = {};

for (const name of (await readdir(dir)).filter(f => f.endsWith('.json')).sort()) {
  const raw = JSON.parse(await readFile(new URL(name, dir), 'utf8'));
  const parsed = parsePortfolioDetailed(raw);
  if ('errors' in parsed) { rows.push(`| ${name} | — | invalid portfolio | | | | | |`); continue; }
  const profile: CandidateProfile = parsed.profile;
  const evidence = extractEvidence(validPortfolio(raw)!, profile.claimed_topics);
  const focus_lane = { domain: profile.domain, skills: profile.skills, topics: profile.claimed_topics };
  const generate = createGenerator({ chat: live ? chat : down, runTests, validateTask, seedBank: () => loadSeedBank(), log: () => {} });
  const legacy = createGenerator({ chat: down, runTests, validateTask, seedBank: () => loadSeedBank(), log: () => {} });
  for (const [label, gen, withEvidence] of [['new', generate, true], ['baseline', legacy, false]] as const) {
    const started = Date.now();
    const result = await gen({ profile, focus_lane, ...(withEvidence ? { evidence } : {}), progress: () => {} }, { signal: AbortSignal.timeout(600_000) });
    const ms = Date.now() - started;
    if (result.kind !== 'ok') { (label === 'new' ? rows : baseline).push(`| ${name.replace('.json', '')} | all | ${result.kind}: ${'message' in result ? result.message : ''} | | | | | ${ms} |`); continue; }
    for (const tier of tiers) {
      const task: PrivateTask = result.value[tier];
      const s = task.selection;
      const line = `| ${name.replace('.json', '')} | ${tier} | ${task.family_id} | ${s?.scenario_id ?? '—'} | ${s ? `${s.project_name} (#${s.project_index})` : '—'} | ${s ? s.method : 'reviewed default'} | ${s ? s.evidence.join(', ') : '—'} | ${tier === 'novice' ? ms : ''} |`;
      (label === 'new' ? rows : baseline).push(line);
    }
    if (label === 'new') summary[name] = tiers.map(t => result.value[t].family_id).join(' / ');
  }
}
const stats = validateTask.stats();
const header = '| portfolio | tier | family | scenario | project | method | evidence (portfolio sources) | prep ms |\n|---|---|---|---|---|---|---|---|';
const report = `# Personalization evaluation (generated by generation/eval-personalization.ts)\n\nRunner: ${process.env.RUNNER ?? 'local'} · Stage B (Featherless): ${live ? 'enabled' : 'not used'} · ${new Date().toISOString()}\n\nEvery row below was certified by K5 (independent oracle, reference x3, starter regression) before being listed.\n\n## Evidence-grounded selection (new)\n\n${header}\n${rows.join('\n')}\n\n## Previous K6 baseline (no project evidence, same provider setting)\n\n${header}\n${baseline.join('\n')}\n\nReceipt cache: ${stats.hits} hits, ${stats.misses} misses, ${stats.stored} stored${stats.disabled ? ' (DISABLED: runner identity unknown)' : ''}.\n`;
console.log(report);
if (out) await writeFile(out, report);
